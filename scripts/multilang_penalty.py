#!/usr/bin/env python3
"""Cross-language tokenizer penalty benchmark on FLORES-200.

Measures how many more tokens each language costs vs English for the **same
content**, across baseline model tokenizers. Uses the token/sentence ratio over
the 1012 sentence-aligned FLORES devtest pairs — robust for scripts without
whitespace word boundaries (Chinese, Thai, ...), unlike tokens/word.

    penalty_x(lang, tokenizer) = tokens(lang) / tokens(English)   [same 1012 sents]

Writes results/multilang-penalty.{json,md}. Run:
`scripts/op-run.sh uv run --no-sync python scripts/multilang_penalty.py`
"""

from __future__ import annotations

import json
import os
from pathlib import Path

from transformers import AutoTokenizer

# User's target languages -> FLORES-200 config (script matters for the file).
_LANGS: dict[str, str] = {
    "de": "deu_Latn",
    "fr": "fra_Latn",
    "es": "spa_Latn",
    "pt": "por_Latn",
    "cs": "ces_Latn",
    "pl": "pol_Latn",
    "ru": "rus_Cyrl",
    "uk": "ukr_Cyrl",
    "lt": "lit_Latn",
    "hi": "hin_Deva",
    "he": "heb_Hebr",
    "ar": "arb_Arab",
    "th": "tha_Thai",
    "zh": "zho_Hans",
}

_BASELINES = [
    "gpt2",
    "mistralai/Mistral-7B-v0.1",
    "meta-llama/Llama-3.1-8B",
    "Qwen/Qwen2.5-7B",
    "deepseek-ai/DeepSeek-V3",
]


def _lines(path: Path) -> list[str]:
    return [
        ln.strip()
        for ln in path.read_text(encoding="utf-8").splitlines()
        if ln.strip()
    ]


def main() -> None:
    """Compute the cross-language penalty matrix and write the report."""
    dd = Path(os.environ["TOKENIZER_DATA_DIR"])
    token = os.environ.get("HF_TOKEN")
    devtest = dd / "flores200" / "flores200_dataset" / "devtest"
    eng = _lines(devtest / "eng_Latn.devtest")

    # tokens(lang) totals per (baseline, lang), + english totals per baseline.
    matrix: dict[str, dict[str, float]] = {}
    for model in _BASELINES:
        try:
            tok = AutoTokenizer.from_pretrained(model, token=token)
        except Exception as err:
            matrix[model] = {"error": str(err)[:100]}
            continue

        def _tot(docs: list[str], tk=None) -> int:
            tk = tk if tk is not None else tok  # noqa: B023
            return sum(
                len(tk.encode(s, add_special_tokens=False)) for s in docs
            )

        eng_tot = _tot(eng)
        row: dict[str, float] = {}
        for code, cfg in _LANGS.items():
            path = devtest / f"{cfg}.devtest"
            if not path.is_file():
                continue
            lang_tot = _tot(_lines(path))
            row[code] = round(lang_tot / eng_tot, 3) if eng_tot else 0.0
        matrix[model] = row

    # Average penalty per language across baselines that loaded.
    avg: dict[str, float] = {}
    for code in _LANGS:
        vals = [
            r[code]
            for r in matrix.values()
            if isinstance(r, dict) and code in r and "error" not in r
        ]
        if vals:
            avg[code] = round(sum(vals) / len(vals), 3)

    out = {
        "metric": "tokens(lang) / tokens(English), same 1012 FLORES sentences",
        "languages": _LANGS,
        "baselines": matrix,
        "avg_penalty_x": avg,
    }
    results = Path("results")
    (results / "multilang-penalty.json").write_text(
        json.dumps(out, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    _write_md(results / "multilang-penalty.md", out)
    print("wrote results/multilang-penalty.{json,md}")
    ranked = sorted(avg.items(), key=lambda kv: kv[1], reverse=True)
    print("worst penalties:", ranked[:5])


def _write_md(path: Path, out: dict) -> None:
    avg = out["avg_penalty_x"]
    ranked = sorted(avg.items(), key=lambda kv: kv[1], reverse=True)
    rows = [
        f"| {code} | {out['languages'][code]} | {mult:.2f}× |"
        for code, mult in ranked
    ]
    lines = [
        "# Cross-language tokenizer penalty (FLORES-200)",
        "",
        "Generated by `scripts/multilang_penalty.py`. "
        f"Metric: {out['metric']}. Averaged over "
        f"{sum(1 for r in out['baselines'].values() if 'error' not in r)} "
        "baseline model tokenizers (gpt2, Mistral, Llama-3.1, Qwen2.5, "
        "DeepSeek-V3).",
        "",
        "| Lang | FLORES | Avg penalty vs English |",
        "|------|--------|-----------------------:|",
        *rows,
        "",
        "Every language costs more tokens than English for identical content — "
        "the motivation for per-language tokenizers. Polish is mid-pack; the "
        "same recipe-driven pipeline (`languages/<iso>/recipe.yaml`) applies to "
        "each. Full per-baseline matrix in `multilang-penalty.json`.",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
