#!/usr/bin/env python3
"""Story 2.4: is a technical-vs-general tokenizer router worth it?

Trains three 32k BPE tokenizers — **general** (Polish prose), **technical**
(code), and **mixed** (both) — and compares four strategies on a prose+code
eval set: use one tokenizer for everything (general / technical / mixed) vs
**route** each document to its domain tokenizer. Also reports router accuracy.

The keep/drop question: does routing beat a single tokenizer trained on the
mixed corpus? If mixed-single is about as good, a union vocab is simpler than
running two tokenizers + a router.

Writes results/routing-experiment.{json,md}. Run:
`scripts/op-run.sh uv run --no-sync python scripts/routing_experiment.py`
"""

from __future__ import annotations

import json
import os
from pathlib import Path

from tokenizers import (
    Tokenizer,
    decoders,
    models,
    normalizers,
    pre_tokenizers,
    trainers,
)

from tokenizer_core.routing import RoutedEncoder, router_accuracy


def _lines(path: Path, limit: int | None = None) -> list[str]:
    out = []
    for ln in path.read_text(encoding="utf-8").splitlines():
        s = ln.strip()
        if s:
            out.append(s)
        if limit and len(out) >= limit:
            break
    return out


def _train_bpe(docs: list[str], vocab_size: int = 32000) -> Tokenizer:
    tok = Tokenizer(models.BPE(unk_token=None))
    tok.normalizer = normalizers.NFC()
    tok.pre_tokenizer = pre_tokenizers.ByteLevel(add_prefix_space=False)
    tok.decoder = decoders.ByteLevel()
    tok.train_from_iterator(
        docs,
        trainers.BpeTrainer(
            vocab_size=vocab_size,
            initial_alphabet=pre_tokenizers.ByteLevel.alphabet(),
        ),
    )
    return tok


def _total_tokens(tok: Tokenizer, docs: list[str]) -> int:
    return sum(len(tok.encode(d).ids) for d in docs)


def main() -> None:
    """Run the routing experiment and write the report + decision."""
    dd = Path(os.environ["TOKENIZER_DATA_DIR"])
    devtest = dd / "flores200" / "flores200_dataset" / "devtest"

    # Train corpora (bounded to keep byte-level BPE memory in check).
    prose_train = _lines(dd / "pl" / "train" / "fineweb2.txt", 5000)
    code_train = _lines(dd / "technical" / "train" / "code.txt", 5000)
    mixed_train = prose_train[:2500] + code_train[:2500]

    general = _train_bpe(prose_train)
    technical = _train_bpe(code_train)
    mixed = _train_bpe(mixed_train)

    # Eval: prose (FLORES Polish) + held-out code.
    prose_eval = _lines(devtest / "pol_Latn.devtest")
    code_eval = _lines(dd / "technical" / "train" / "code_eval.txt")
    all_eval = prose_eval + code_eval

    routed = RoutedEncoder({"general": general, "technical": technical})

    labeled = [(d, "general") for d in prose_eval] + [
        (d, "technical") for d in code_eval
    ]
    acc = router_accuracy(labeled)

    totals = {
        "general_only": _total_tokens(general, all_eval),
        "technical_only": _total_tokens(technical, all_eval),
        "mixed_only": _total_tokens(mixed, all_eval),
        "routed": sum(len(routed.encode(d)) for d in all_eval),
    }
    best_single = min(
        totals["general_only"], totals["technical_only"], totals["mixed_only"]
    )
    routed_vs_mixed = (1 - totals["routed"] / totals["mixed_only"]) * 100
    routed_vs_best = (1 - totals["routed"] / best_single) * 100

    # Keep/drop: routing must beat the mixed single tokenizer by a clear margin
    # to justify running two tokenizers + a router.
    keep = routed_vs_mixed >= 5.0 and acc >= 0.95
    decision = "KEEP" if keep else "DROP"

    out = {
        "eval": f"{len(prose_eval)} FLORES-pl prose + {len(code_eval)} code docs",
        "router_accuracy": round(acc, 4),
        "total_tokens": totals,
        "routed_vs_mixed_pct": round(routed_vs_mixed, 1),
        "routed_vs_best_single_pct": round(routed_vs_best, 1),
        "decision": decision,
    }
    results = Path("results")
    (results / "routing-experiment.json").write_text(
        json.dumps(out, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    _write_md(results / "routing-experiment.md", out)
    print(
        f"router acc {acc:.3f}; routed {totals['routed']} vs mixed "
        f"{totals['mixed_only']} tokens ({routed_vs_mixed:+.1f}%). {decision}"
    )


def _write_md(path: Path, out: dict) -> None:
    t = out["total_tokens"]
    lines = [
        "# Technical-vs-general tokenizer router (Story 2.4)",
        "",
        f"Generated by `scripts/routing_experiment.py` on {out['eval']}. Total "
        "tokens to encode the whole prose+code eval set under each strategy "
        "(lower is better); three 32k BPE tokenizers (general=Polish prose, "
        "technical=code, mixed=both).",
        "",
        "| Strategy | Total tokens |",
        "|----------|-------------:|",
        f"| general-only | {t['general_only']:,} |",
        f"| technical-only | {t['technical_only']:,} |",
        f"| mixed-only | {t['mixed_only']:,} |",
        f"| **routed** | **{t['routed']:,}** |",
        "",
        f"Router accuracy (prose vs code): **{out['router_accuracy'] * 100:.1f}%**. "
        + (
            f"Routing uses **{out['routed_vs_mixed_pct']}%** fewer tokens than "
            "the mixed single tokenizer."
            if out["routed_vs_mixed_pct"] > 0
            else f"Routing uses **{-out['routed_vs_mixed_pct']}% more** tokens "
            "than the mixed single tokenizer - the mixed tokenizer wins."
        ),
        "",
        f"## Decision: {out['decision']}",
        "",
        "Criterion: keep routing only if it beats a single tokenizer trained on "
        "the mixed corpus by >=5% with an accurate router (>=95%). "
        + (
            "It does - routing is worth the extra deployment complexity."
            if out["decision"] == "KEEP"
            else "It does not: a single tokenizer trained on the mixed corpus "
            "is both simpler and more efficient. It allocates vocab across both "
            "domains and handles their overlap (English identifiers in code, "
            "symbols in prose), whereas two hard-switched specialists each waste "
            "vocab and the router mis-routes some inputs. Prefer one "
            "mixed-domain tokenizer over a technical/general router."
        ),
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
