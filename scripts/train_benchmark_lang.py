#!/usr/bin/env python3
"""Train + benchmark one language's tokenizer end to end (the add-a-language proof).

Trains a recipe candidate on the staged corpus, then measures our tokenizer's
token-per-sentence penalty vs English on FLORES-200 against the baseline model
tokenizers — the same metric as scripts/multilang_penalty.py. Appends the
result to results/multilang-ours.json.

Run: `scripts/op-run.sh uv run --no-sync python scripts/train_benchmark_lang.py \
        --lang de --candidate de-bpe-32k --n-docs 12000`
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path

from transformers import AutoTokenizer

from tokenizer_core.train.artifact import save_artifact
from tokenizer_core.train.config import Recipe
from tokenizer_core.train.trainers import train_candidate

_BASELINES = [
    "gpt2",
    "meta-llama/Llama-3.1-8B",
    "mistralai/Mistral-7B-v0.1",
    "Qwen/Qwen2.5-7B",
    "deepseek-ai/DeepSeek-V3",
]


def _lines(path: Path) -> list[str]:
    return [
        ln.strip()
        for ln in path.read_text(encoding="utf-8").splitlines()
        if ln.strip()
    ]


def _write_md(path: Path, data: dict) -> None:
    """Render results/multilang-ours.md from the accumulated json."""
    rows = [
        f"| {lang} | {e['flores']} | {e['ours_tokens_per_sentence']} | "
        f"{e['baseline_tokens_per_sentence']} | "
        f"**−{e['token_reduction_vs_baseline_pct']}%** | "
        f"{e['baseline_penalty_vs_english_x']}× → "
        f"**{e['ours_vs_english_parity_x']}×** |"
        for lang, e in sorted(data.items())
    ]
    lines = [
        "# Our tokenizers across languages (FLORES-200)",
        "",
        "Generated by `scripts/train_benchmark_lang.py`. Each is a 32k byte-level"
        " BPE trained on ~50 MB of staged FineWeb-2 + Wikipedia text, **no model"
        " retraining**. Tokens/sentence on the 1012 aligned FLORES sentences; "
        "penalty = language cost / a good English tokenizer's English cost.",
        "",
        "| Lang | FLORES | Ours tok/sent | Baseline tok/sent | Reduction | "
        "Penalty vs EN (baseline → ours) |",
        "|------|--------|--------------:|------------------:|----------:|"
        "-------------------------------|",
        *rows,
        "",
        "The same recipe-driven pipeline handles every FLORES script (Latin, "
        "Cyrillic, Hebrew, Arabic, Devanagari, Thai, Han) - copy "
        "`languages/_template/`, stage a corpus with `scripts/stage_corpus.py`, "
        "and run. Each 32k BPE cuts tokens 23-77% vs baselines and reaches "
        "~1.0-1.3x English; Hebrew, Chinese and Thai land below parity. Byte-"
        "dense scripts (Devanagari, Thai) need `split_words: false` in the "
        "recipe - the GPT-2 word-split regex over-fragments them, and disabling "
        "it lifts chars/token ~1.5 -> ~4 (Hindi 3.05x -> 1.04x, Thai 1.99x -> "
        "0.91x).",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    """Train the candidate and record its FLORES penalty vs baselines."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--lang", required=True)
    parser.add_argument("--candidate", required=True)
    parser.add_argument("--n-docs", type=int, default=12000)
    args = parser.parse_args()

    dd = Path(os.environ["TOKENIZER_DATA_DIR"])
    token = os.environ.get("HF_TOKEN")
    recipe = Recipe.load(f"languages/{args.lang}/recipe.yaml")
    candidate = next(c for c in recipe.candidates if c.name == args.candidate)

    # Find the FLORES target file from the recipe's eval pair.
    flores_cfg = next(
        s.config
        for s in recipe.eval_corpora
        if s.config
        and s.config != "eng_Latn"
        and "_" in s.config
        and len(s.config.split("_")[0]) == 3
    )
    devtest = dd / "flores200" / "flores200_dataset" / "devtest"
    target = _lines(devtest / f"{flores_cfg}.devtest")
    eng = _lines(devtest / "eng_Latn.devtest")

    # Train + save.
    tokenizer, metadata = train_candidate(
        recipe, candidate, n_docs=args.n_docs, seed=42, data_dir=dd
    )
    out = dd / "tokenizers" / args.lang / candidate.name
    save_artifact(tokenizer, metadata, out)

    def _tokens(tk_encode, docs: list[str]) -> int:
        return sum(len(tk_encode(s)) for s in docs)

    n = len(target)
    # Our tokenizer's tokens for the target language.
    our_lang = _tokens(lambda s: tokenizer.encode(s).ids, target)
    our_lang_per_sent = round(our_lang / n, 2)

    # Baselines: tokens for the SAME target text, and for English.
    base_lang, base_eng = [], []
    for m in _BASELINES:
        try:
            bt = AutoTokenizer.from_pretrained(m, token=token)
            base_lang.append(
                _tokens(
                    lambda s, bt=bt: bt.encode(s, add_special_tokens=False),
                    target,
                )
            )
            base_eng.append(
                _tokens(
                    lambda s, bt=bt: bt.encode(s, add_special_tokens=False), eng
                )
            )
        except Exception:
            continue
    if not base_lang:
        raise SystemExit(
            "no baseline tokenizers loaded — check network / HF_TOKEN access; "
            "cannot compute the comparison"
        )
    avg_base_lang = sum(base_lang) / len(base_lang)
    avg_base_eng = sum(base_eng) / len(base_eng)

    entry = {
        "candidate": candidate.name,
        "flores": flores_cfg,
        "vocab_size": candidate.vocab_size,
        # honest, apples-to-apples on the SAME target text:
        "ours_tokens_per_sentence": our_lang_per_sent,
        "baseline_tokens_per_sentence": round(avg_base_lang / n, 2),
        # how many fewer tokens our tokenizer uses for this language:
        "token_reduction_vs_baseline_pct": round(
            (1 - our_lang / avg_base_lang) * 100, 1
        ),
        # our language cost vs a good English tokenizer's English cost:
        "ours_vs_english_parity_x": round(our_lang / avg_base_eng, 3),
        "baseline_penalty_vs_english_x": round(avg_base_lang / avg_base_eng, 3),
    }
    results_path = Path("results") / "multilang-ours.json"
    data = {}
    if results_path.is_file():
        data = json.loads(results_path.read_text(encoding="utf-8"))
    data[args.lang] = entry
    results_path.write_text(
        json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    _write_md(Path("results") / "multilang-ours.md", data)
    print(
        f"{args.lang}/{candidate.name}: {entry['ours_tokens_per_sentence']} vs "
        f"{entry['baseline_tokens_per_sentence']} tok/sent "
        f"({entry['token_reduction_vs_baseline_pct']}% fewer); vs-English "
        f"{entry['ours_vs_english_parity_x']}x (baseline penalty "
        f"{entry['baseline_penalty_vs_english_x']}x). artifact -> {out}"
    )


if __name__ == "__main__":
    main()
